import type { BrandProfile } from '../types/ai.types.js';

export type CaptionTone =
  | 'formal'
  | 'friendly'
  | 'sales'
  | 'educational'
  | 'storytelling'
  | 'professional'
  | 'luxury'
  | 'inspirational'
  | 'funny';

const toneGuide: Record<CaptionTone, string> = {
  formal: `
لحن رسمی:
- زبان معیار، دقیق و بدون محاوره.
- با یک واقعیت یا مسئله مهم مرتبط با موضوع شروع کن.
- از «می‌تونی»، «چی»، «آها» و زبان شکسته استفاده نکن.
- حس یک برند معتبر و مسئولیت‌پذیر داشته باشد.
`,

  friendly: `
لحن صمیمی:
- مستقیم با مخاطب حرف بزن (تو/شما به‌صورت گرم).
- با یک موقعیت روزمره و قابل لمس از زندگی مخاطب شروع کن.
- جمله‌ها کوتاه، روان و گفت‌وگویی باشند.
- می‌توانی سؤال بپرسی، اما مصنوعی نباشد.
`,

  sales: `
لحن فروش‌محور:
- با یک نیاز یا مشکل واقعی مخاطب شروع کن.
- پیامد نادیده گرفتن موضوع را کوتاه و بدون اغراق بگو.
- ارزش راهکار مرتبط با موضوع را روشن کن.
- CTA باید یک اقدام مشخص تجاری داشته باشد (مشاوره، خرید، ثبت‌نام و ...).
`,

  educational: `
لحن آموزشی:
- مثل یک راهنمای کاربردی بنویس، نه یک متن تبلیغاتی.
- اگر موضوع شامل چند اشتباه، نکته یا مرحله است (مثلاً ۵ اشتباه)، آن‌ها را شماره‌دار یا با نشانه‌گذاری کوتاه در متن بیاور.
- برای هر مورد یک جمله کوتاه و قابل اجرا بنویس؛ فقط نام نبر و رد شو.
- در پایان یک جمع‌بندی عملی بده که مخاطب بداند قدم بعدی چیست.
- از کلی‌گویی مثل «مهم است» یا «باید توجه کنید» بدون توضیح خودداری کن.
`,

  storytelling: `
لحن داستانی:
- یک روایت کوتاه فرضی بساز که شخصیت آن از میان مخاطبان همین کسب‌وکار باشد.
- مسئله شخصیت باید همان موضوع ورودی باشد.
- پایان روایت را به پیام اصلی موضوع وصل کن.
- داستان خیالی بی‌ربط ممنوع.
`,

  professional: `
لحن حرفه‌ای:
- تحلیلی و تخصصی بنویس.
- از زاویه فرآیند، تصمیم‌گیری و مدیریت به موضوع نگاه کن.
- یک بینش مشخص بده، نه شعار کلی.
`,

  luxury: `
لحن لوکس:
- جملات کوتاه، آرام و دقیق بنویس؛ حس اطمینان و ظرافت بده.
- به‌جای شعار، روی کیفیت ارتباط، دقت در جزئیات و ارزش بلندمدت تمرکز کن.
- از کلمات پرطمطراق، اغراق و فروش مستقیم تند پرهیز کن.
- لحن باید شبیه برند سطح‌بالا باشد: کمتر حرف بزند، اما وزین و انتخاب‌شده.
- موضوع را حفظ کن؛ لوکس بودن به معنی عوض کردن موضوع به مد یا تجملات نیست.
- CTA باید آرام و محترمانه باشد، نه فشار فروش.
`,

  inspirational: `
لحن الهام‌بخش:
- با یک بینش مرتبط با موضوع شروع کن.
- مخاطب را به یک اقدام کوچک و واقعی دعوت کن.
- شعار کلیشه‌ای مثل «موفقیت اتفاقی نیست» ممنوع.
`,

  funny: `
لحن طنز:
- از یک موقعیت بامزه و واقعی مرتبط با موضوع/کسب‌وکار شروع کن
  (مثلاً فراموشی پیگیری، شلوغی کار، اشتباه رایج مشتری یا فروشنده).
- یک غافلگیری یا تضاد خنده‌دار داشته باش.
- بعد از شوخی، پیام اصلی موضوع را حفظ کن.
- شوخی نامرتبط یا زورکی ممنوع.
`,
};

export function captionPrompt(
  profile: BrandProfile,
  topic: string,
  tone: CaptionTone,
): string {
  return `
تو یک کپی‌رایتر حرفه‌ای فارسی‌زبان برای اینستاگرام هستی.

## موضوع اجباری (تنها محور کپشن)
${topic}

## پروفایل برند (دقیقاً همین را رعایت کن)
- نوع کسب‌وکار: ${profile.businessType}
- مخاطب هدف: ${profile.targetAudience}
- هدف تجاری: ${profile.goal}
- هندل اینستاگرام: ${profile.instagramHandle}

قواعد پروفایل:
- نوع کسب‌وکار را عوض نکن.
- مخاطب هدف را جدی بگیر.
- متن برای همین کسب‌وکار و همین مخاطب نوشته شود.

## لحن این کپشن (حتماً متمایز باشد)
${tone}
${toneGuide[tone]}

مهم درباره لحن:
- این کپشن فقط با لحن «${tone}» نوشته شود.
- اگر لحن طنز است، متن باید واقعاً کمی بامزه باشد.
- اگر لحن رسمی است، نباید شبیه متن صمیمی شود.
- اگر لحن آموزشی است، باید نکته یاد بدهد، نه فقط تعریف کلی.
- لحن‌های مختلف نباید متن تقریباً یکسانی تولید کنند.

## قوانین محتوا

1. موضوع ورودی مرجع اصلی و غیرقابل تغییر کپشن است.
2. تمام نکات اصلی موضوع را پوشش بده؛ هیچ مورد مهمی را حذف نکن.
3. اگر موضوع شامل تعداد مشخصی مورد است (مثلاً ۵ اشتباه)،
   تمام آن موارد را در کپشن حفظ کن.
4. ترتیب و معنای نکات موضوع را تغییر نده و مورد جدیدی از خودت اضافه نکن.
5. نوع کسب‌وکار و مخاطب هدف را برای انتخاب مثال‌ها و واژگان به کار ببر،
   نه برای تغییر موضوع اصلی.
6. اگر موضوع درباره یک ابزار یا مفهوم تخصصی است،
   آن را به همان موضوع محدود نگه دار؛ حتی اگر کسب‌وکار برند حوزه دیگری باشد.
7. قابلیت، آمار، نتیجه قطعی، نام مشتری یا داستان واقعی تأییدنشده اختراع نکن.
8. در داستان‌پردازی، فرضی بودن روایت را حفظ کن و آن را تجربه واقعی برند معرفی نکن.
9. متن باید بین ۷۰ تا ۱۴۰ کلمه و شامل ۲ تا ۳ پاراگراف باشد.
10. فارسی طبیعی، روان و متناسب با لحن درخواستی بنویس.
11. CTA جداگانه، مرتبط با موضوع و هدف برند باشد.
12. بین ۳ تا ۵ هشتگ مرتبط تولید کن.
13. هیچ بخش از کپشن نباید صرفاً برای پر کردن تعداد کلمات یا جذاب‌تر شدن،
    از موضوع اصلی فاصله بگیرد.

## خروجی فقط JSON

{
  "tone": "${tone}",
  "text": "متن کپشن",
  "cta": "دعوت به اقدام",
  "hashtags": ["#هشتگ۱", "#هشتگ۲", "#هشتگ۳"]
}

فقط JSON برگردان.
`;
}
