import type { BrandProfile } from '../types/ai.types.js';

interface ReelPromptInput {
  profile: BrandProfile;
  topic: string;
  durationSec: number;
}

export function reelPrompt({
  profile,
  topic,
  durationSec,
}: ReelPromptInput): string {
  return `
تو یک سناریونویس حرفه‌ای ریلز اینستاگرام برای بازار ایران هستی.

## موضوع اجباری ریلز
${topic}

## پروفایل برند (دقیقاً همین را رعایت کن)
- نوع کسب‌وکار: ${profile.businessType}
- مخاطب هدف: ${profile.targetAudience}
- هدف تجاری: ${profile.goal}
- هندل: ${profile.instagramHandle}

قواعد پروفایل:
- نوع کسب‌وکار را عوض نکن.
- مخاطب هدف را جدی بگیر.
- سناریو برای همین کسب‌وکار و همین مخاطب باشد.

## مدت کل ویدیو
${durationSec} ثانیه

## ساختار خروجی JSON

{
  "topic": "${topic}",
  "durationSec": ${durationSec},
  "hook": "قلاب ۳ ثانیه اول",
  "scenes": [
    {
      "order": 1,
      "visual": "دستور فیلمبرداری واضح و قابل اجرا با موبایل",
      "voiceover": "گفتار محاوره‌ای طبیعی",
      "durationSec": 5
    }
  ],
  "cta": "دعوت به اقدام مشخص",
  "hashtags": ["#هشتگ۱", "#هشتگ۲", "#هشتگ۳", "#هشتگ۴", "#هشتگ۵"],
  "musicMood": "سبک و حس موسیقی"
}

## قوانین سخت

1. بین ۳ تا ۶ صحنه بساز.
2. مجموع durationSec همه صحنه‌ها باید دقیقاً ${durationSec} باشد.
3. order از ۱ شروع شود و پشت‌سرهم باشد.

4. Hook (خیلی مهم):
   - حداکثر یک جمله کوتاه.
   - باید در ۳ ثانیه اول توقف ایجاد کند.
   - از یکی از این الگوها استفاده کن:
     - سؤال تند و مشخص
     - عدد + ادعا (مثلاً ۳ اشتباه / ۲ انتخاب)
     - تضاد یا غافلگیری مرتبط با موضوع
   - ممنوع: جمله‌های کلی مثل «فصل جدید رسید» یا «وقت لباس جدیده» به‌تنهایی.
   - املا و دستور زبان فارسی باید درست باشد.

5. Visual:
   - دستور فیلمبرداری روشن: زاویه، سوژه، حرکت، لوکیشن ساده.
   - با موبایل قابل اجرا باشد.
   - از واژه‌های مبهم یا ترجمه‌ای مثل «کامرایی» استفاده نکن.
   - مثال خوب: «کلوزآپ یقه پالتو روی رگال»، «مدل از کمر به بالا در حال پرو»، «دست در حال ورق زدن هودی‌ها».

6. Voiceover (خیلی مهم):
   - فارسی محاوره‌ای طبیعی، درست و روان.
   - هر صحنه یک پیام جدا و مفید داشته باشد؛ تکرار ممنوع.
   - جمله‌های غلط یا ترجمه‌ای ممنوع، از جمله:
     - «روی شما می‌پوشون»
     - «روی شما نشان دهید»
     - «بهتر از پاییز روی شما بزاره»
   - به‌جای آن طبیعی بنویس، مثلاً:
     - «این پالتو با هر شلواری ست می‌شه»
     - «اگه دنبال رنگ گرم برای پاییزی، اینا رو ببین»
   - لحن متناسب با مخاطب هدف باشد.
   - از اسم برند یا هندل حداکثر در یک صحنه استفاده کن، نه در همه صحنه‌ها.

7. صحنه‌ها نباید تکراری باشند. هر صحنه زاویه یا اطلاعات جدید اضافه کند.

8. کل سناریو فقط درباره موضوع بالا باشد.

9. CTA متناسب با هدف برند (${profile.goal}) و مشخص باشد. یک اقدام واضح بگو.

10. دقیقاً ۵ تا ۸ هشتگ مرتبط بساز.

11. musicMood فقط سبک و حس را بگوید، نه نام آهنگ.

12. قابلیت یا آمار تأییدنشده به محصول نسبت نده.

فقط JSON معتبر برگردان.
`;
}
